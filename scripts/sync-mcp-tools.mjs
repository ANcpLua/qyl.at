// Writes src/data/mcp-tools.ts from qyl's MCP tool snapshot, the file the MCP server's own
// tests hold its registered tools and skill resources to. Every tool and skill the site
// names comes from that generated module, so a tool renamed or removed in qyl disappears
// from the site with the next sync instead of surviving in prose.
//
//   node scripts/sync-mcp-tools.mjs [path/to/tool-manifest.snapshot.json]
//
// The default is the qyl checkout beside this one.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = path.resolve(
  process.argv[2] ?? path.join(root, "..", "qyl", "services", "qyl.mcp", "tool-manifest.snapshot.json"),
);
const snapshot = JSON.parse(fs.readFileSync(source, "utf8"));

function required(value, what) {
  if (typeof value !== "string" || value.trim() === "") throw new Error(`${source}: ${what} is missing`);
  return value;
}

const tools = snapshot.tools
  .map((tool) => {
    const name = required(tool.name, "a tool name");
    const scopes = (tool.meta?.securitySchemes ?? []).flatMap((scheme) => scheme.scopes ?? []);
    if (scopes.length === 0) throw new Error(`${source}: ${name} declares no OAuth scope`);
    return {
      name,
      title: required(tool.title, `${name} title`),
      description: required(tool.description, `${name} description`),
      scopes,
      readOnly: tool.annotations?.readOnlyHint === true,
      destructive: tool.annotations?.destructiveHint === true,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// A skill is published as resources under skill://<server>/<skill>/<file>; its SKILL.md
// resource carries the skill's front-matter description.
const skills = (snapshot.resources ?? [])
  .filter((resource) => /^skill:\/\/[^/]+\/[^/]+\/SKILL\.md$/u.test(resource.uri))
  .map((resource) => ({
    name: resource.uri.split("/")[3],
    description: required(resource.description, `${resource.uri} description`),
  }));

const target = path.join(root, "src", "data", "mcp-tools.ts");
fs.writeFileSync(
  target,
  [
    "// Generated by scripts/sync-mcp-tools.mjs from qyl's MCP tool snapshot. Do not edit;",
    "// run `bun run sync:tools` after the MCP server's tools or skills change.",
    `export const mcpTools = ${JSON.stringify(tools, null, 2)} as const;`,
    "",
    `export const mcpSkills = ${JSON.stringify(skills, null, 2)} as const;`,
    "",
  ].join("\n"),
);
console.log(`${path.relative(root, target)}: ${tools.length} tools, ${skills.length} skill(s) from ${source}`);
